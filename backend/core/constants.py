# ---------------- 旺衰（以月建论） ----------------
def wangshuai(month_el, el):
    """月建五行 vs 爻五行 -> 旺/相/休/囚/死"""
    if el == month_el:
        return "旺"          # 当令者旺
    if sheng(month_el, el):
        return "相"          # 月所生者相
    if sheng(el, month_el):
        return "休"          # 生月者休
    if ke(el, month_el):
        return "囚"          # 克月者囚
    return "死"              # 月所克者死


