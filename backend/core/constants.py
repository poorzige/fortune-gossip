def xunkong(day_gz):
    """由日干支求旬空（空亡二支）"""
    for idx in range(60):
        gz = TIANGAN[idx % 10] + DIZHI[idx % 12]
        if gz == day_gz:
            head = idx - idx % 10
            head_gz = TIANGAN[head % 10] + DIZHI[head % 12]
            return XUN_KONG[head_gz]
    return ""


