def _hex_lines(lower, upper):
    """由上下卦得六爻（自下而上）"""
    return tuple(BAGUA[lower]["lines"]) + tuple(BAGUA[upper]["lines"])


def full_name(name, lower, upper):
    """卦之全名，如 天火同人；八纯卦为 乾为天"""
    if lower == upper:
        return f"{name}为{BAGUA[upper]['xiang']}"
    return f"{BAGUA[upper]['xiang']}{BAGUA[lower]['xiang']}{name}"


